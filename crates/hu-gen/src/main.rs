//! Writes synthetic Abaqus / Nastran input decks of roughly a given size,
//! for exercising the editor on huge files:
//!
//!     hu-gen abaqus  2G  block.inp     # hex block, C3D8R
//!     hu-gen nastran 30G plates.bdf    # stacked plates, GRID* + CQUAD4
//!
//! The Nastran deck mixes all three field formats: GRID* in large field,
//! CQUAD4 in small field, and CQUAD4 in free field once IDs outgrow eight
//! columns (above ~15 GB).

use std::fs::File;
use std::io::{self, BufWriter, Write};
use std::process::ExitCode;
use std::time::Instant;

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let (Some(format), Some(target), Some(path)) = (
        args.first(),
        args.get(1).and_then(|s| parse_size(s)),
        args.get(2),
    ) else {
        eprintln!("usage: hu-gen <abaqus|nastran> <size, e.g. 500M or 30G> <output>");
        return ExitCode::FAILURE;
    };
    let write: fn(&mut BufWriter<File>, u64) -> io::Result<()> = match format.as_str() {
        "abaqus" => abaqus,
        "nastran" => nastran,
        other => {
            eprintln!("unknown format `{other}`; expected abaqus or nastran");
            return ExitCode::FAILURE;
        }
    };

    let started = Instant::now();
    let result = File::create(path).and_then(|file| {
        let mut out = BufWriter::with_capacity(8 << 20, file);
        write(&mut out, target)?;
        out.flush()?;
        out.get_ref().metadata()
    });
    match result {
        Ok(meta) => {
            let secs = started.elapsed().as_secs_f64();
            let gib = meta.len() as f64 / (1u64 << 30) as f64;
            eprintln!(
                "wrote {path}: {gib:.2} GiB in {secs:.1} s ({:.2} GiB/s)",
                gib / secs
            );
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("{path}: {e}");
            ExitCode::FAILURE
        }
    }
}

/// `500M`, `2G`, `1.5G`, `4096` (binary units).
fn parse_size(s: &str) -> Option<u64> {
    let (number, unit) = match s.char_indices().last()? {
        (i, c) if c.is_ascii_alphabetic() => (&s[..i], c.to_ascii_uppercase()),
        _ => (s, 'B'),
    };
    let shift = match unit {
        'B' => 0,
        'K' => 10,
        'M' => 20,
        'G' => 30,
        _ => return None,
    };
    Some((number.parse::<f64>().ok()? * (1u64 << shift) as f64) as u64)
}

// Abaqus: an NX × NY × NZ block of C3D8R hexes. Fixed-width columns keep
// every line the same length, so the layer count for a target size is exact.

const AB_NX: u64 = 100;
const AB_NY: u64 = 100;
/// Element layers per `*Element` block, so the deck has structure to outline.
const AB_LAYERS_PER_BLOCK: u64 = 500;
const ID_W: usize = 10;
const COORD_W: usize = 12;
const AB_NODE_LINE: u64 = (ID_W + 3 * (2 + COORD_W) + 1) as u64;
const AB_ELEM_LINE: u64 = (ID_W + 8 * (2 + ID_W) + 1) as u64;

fn abaqus(out: &mut impl Write, target: u64) -> io::Result<()> {
    let per_layer = AB_NX * AB_NY * AB_NODE_LINE + (AB_NX - 1) * (AB_NY - 1) * AB_ELEM_LINE;
    let nz = (target / per_layer).max(2);
    let node = |i: u64, j: u64, k: u64| 1 + i + AB_NX * (j + AB_NY * k);
    let nodes = AB_NX * AB_NY * nz;
    let elements = (AB_NX - 1) * (AB_NY - 1) * (nz - 1);

    write!(
        out,
        "*Heading\n\
         ** Job name: hu-gen Model name: BLOCK\n\
         ** Generated by hu-gen: {nodes} nodes, {elements} C3D8R elements\n\
         *Preprint, echo=NO, model=NO, history=NO, contact=NO\n\
         **\n** PARTS\n**\n\
         *Part, name=BLOCK\n\
         *Node\n"
    )?;
    let mut line = Vec::with_capacity(256);
    for k in 0..nz {
        for j in 0..AB_NY {
            for i in 0..AB_NX {
                line.clear();
                int(&mut line, node(i, j, k), ID_W);
                for c in [i, j, k] {
                    line.extend_from_slice(b", ");
                    fixed(&mut line, c * 25_000, 4, COORD_W);
                }
                line.push(b'\n');
                out.write_all(&line)?;
            }
        }
    }

    let mut element = 0;
    let mut blocks = Vec::new();
    for k in 0..nz - 1 {
        if k % AB_LAYERS_PER_BLOCK == 0 {
            let name = format!("LAYERS_{:04}", blocks.len() + 1);
            writeln!(out, "*Element, type=C3D8R, elset={name}")?;
            blocks.push(name);
        }
        for j in 0..AB_NY - 1 {
            for i in 0..AB_NX - 1 {
                element += 1;
                line.clear();
                int(&mut line, element, ID_W);
                for n in [
                    node(i, j, k),
                    node(i + 1, j, k),
                    node(i + 1, j + 1, k),
                    node(i, j + 1, k),
                    node(i, j, k + 1),
                    node(i + 1, j, k + 1),
                    node(i + 1, j + 1, k + 1),
                    node(i, j + 1, k + 1),
                ] {
                    line.extend_from_slice(b", ");
                    int(&mut line, n, ID_W);
                }
                line.push(b'\n');
                out.write_all(&line)?;
            }
        }
    }

    writeln!(
        out,
        "*Nset, nset=BOTTOM, generate\n 1, {}, 1",
        AB_NX * AB_NY
    )?;
    writeln!(
        out,
        "*Nset, nset=TOP, generate\n {}, {nodes}, 1",
        node(0, 0, nz - 1)
    )?;
    writeln!(out, "*Elset, elset=ALL")?;
    for names in blocks.chunks(8) {
        writeln!(out, " {}", names.join(", "))?;
    }
    out.write_all(
        b"** Section: STEEL-SECTION\n\
          *Solid Section, elset=ALL, material=STEEL\n\
          ,\n\
          *End Part\n\
          **\n** ASSEMBLY\n**\n\
          *Assembly, name=Assembly\n\
          **\n\
          *Instance, name=BLOCK-1, part=BLOCK\n\
          *End Instance\n\
          **\n\
          *End Assembly\n\
          **\n** MATERIALS\n**\n\
          *Material, name=STEEL\n\
          *Density\n 7.85e-09,\n\
          *Elastic\n 210000., 0.3\n\
          **\n** STEP: Load\n**\n\
          *Step, name=Load, nlgeom=NO\n\
          *Static\n1., 1., 1e-05, 1.\n\
          **\n** BOUNDARY CONDITIONS\n**\n\
          *Boundary\nBLOCK-1.BOTTOM, ENCASTRE\n\
          **\n** LOADS\n**\n\
          *Cload\nBLOCK-1.TOP, 3, -1.\n\
          **\n** OUTPUT REQUESTS\n**\n\
          *Output, field, variable=PRESELECT\n\
          *Output, history, variable=PRESELECT\n\
          *End Step\n",
    )
}

// Nastran: NZ stacked NX × NY plates of CQUAD4 shells.

const NA_NX: u64 = 200;
const NA_NY: u64 = 200;
/// `GRID*` in large field: a 72-column line and a 24-column continuation.
const NA_GRID_BYTES: u64 = 73 + 25;
const NA_QUAD_BYTES: u64 = 57;
/// Largest ID that fits an 8-column small field.
const SMALL_FIELD_MAX: u64 = 99_999_999;

fn nastran(out: &mut impl Write, target: u64) -> io::Result<()> {
    let per_plate = NA_NX * NA_NY * NA_GRID_BYTES + (NA_NX - 1) * (NA_NY - 1) * NA_QUAD_BYTES;
    let nz = (target / per_plate).max(1);
    let grid = |i: u64, j: u64, k: u64| 1 + i + NA_NX * (j + NA_NY * k);
    let grids = NA_NX * NA_NY * nz;
    let quads = (NA_NX - 1) * (NA_NY - 1) * nz;

    write!(
        out,
        "$ Generated by hu-gen: {grids} GRIDs, {quads} CQUAD4s in {nz} plates\n\
         SOL 101\n\
         CEND\n\
         TITLE = hu-gen synthetic plates\n\
         ECHO = NONE\n\
         SPC = 1\n\
         SUBCASE 1\n\
         \x20 LABEL = Pressure\n\
         \x20 LOAD = 2\n\
         \x20 DISPLACEMENT(PLOT) = ALL\n\
         \x20 STRESS(PLOT) = ALL\n\
         BEGIN BULK\n\
         PARAM   POST    -1\n\
         $\n\
         $ Material and property\n\
         MAT1    1       210000.         0.3     7.85-9\n\
         PSHELL  1       1       1.\n"
    )?;

    let mut line = Vec::with_capacity(256);
    for k in 0..nz {
        writeln!(out, "$\n$ Plate {} grids (large field)", k + 1)?;
        for j in 0..NA_NY {
            for i in 0..NA_NX {
                line.clear();
                line.extend_from_slice(b"GRID*   ");
                int(&mut line, grid(i, j, k), 16);
                line.extend_from_slice(&[b' '; 16]);
                real(&mut line, i * 25, 16);
                real(&mut line, j * 25, 16);
                line.extend_from_slice(b"\n*       ");
                real(&mut line, k * 100, 16);
                line.push(b'\n');
                out.write_all(&line)?;
            }
        }
    }

    let mut element = 0;
    for k in 0..nz {
        writeln!(out, "$\n$ Plate {} elements", k + 1)?;
        for j in 0..NA_NY - 1 {
            for i in 0..NA_NX - 1 {
                element += 1;
                let fields = [
                    element,
                    1,
                    grid(i, j, k),
                    grid(i + 1, j, k),
                    grid(i + 1, j + 1, k),
                    grid(i, j + 1, k),
                ];
                line.clear();
                if element.max(fields[4]) <= SMALL_FIELD_MAX {
                    line.extend_from_slice(b"CQUAD4  ");
                    for f in fields {
                        int(&mut line, f, 8);
                    }
                } else {
                    line.extend_from_slice(b"CQUAD4");
                    for f in fields {
                        line.push(b',');
                        int(&mut line, f, 0);
                    }
                }
                line.push(b'\n');
                out.write_all(&line)?;
            }
        }
    }

    write!(
        out,
        "$\n\
         $ Constraints and loads\n\
         SPC1    1       123456  1       THRU    {}\n\
         FORCE   2       {:<8}0       1.      0.      0.      -1.\n\
         ENDDATA\n",
        NA_NX,
        grid(NA_NX / 2, NA_NY / 2, 0),
    )
}

/// Appends `value` right-aligned in `width` columns.
fn int(line: &mut Vec<u8>, value: u64, width: usize) {
    let mut buf = itoa::Buffer::new();
    let digits = buf.format(value).as_bytes();
    pad(line, width, digits.len());
    line.extend_from_slice(digits);
}

/// Appends `ticks / 10^decimals` with exactly `decimals` decimals,
/// right-aligned in `width` columns.
fn fixed(line: &mut Vec<u8>, ticks: u64, decimals: u32, width: usize) {
    let scale = 10u64.pow(decimals);
    let mut buf = itoa::Buffer::new();
    let whole = buf.format(ticks / scale).as_bytes();
    pad(line, width, whole.len() + 1 + decimals as usize);
    line.extend_from_slice(whole);
    line.push(b'.');
    let mut buf = itoa::Buffer::new();
    let fraction = buf.format(ticks % scale).as_bytes();
    line.resize(line.len() + decimals as usize - fraction.len(), b'0');
    line.extend_from_slice(fraction);
}

/// Appends `tenths / 10` in Nastran's short real form (`0.`, `2.5`, `10.`),
/// right-aligned in `width` columns.
fn real(line: &mut Vec<u8>, tenths: u64, width: usize) {
    let mut buf = itoa::Buffer::new();
    let whole = buf.format(tenths / 10).as_bytes();
    let tenth = tenths % 10;
    pad(line, width, whole.len() + 1 + usize::from(tenth != 0));
    line.extend_from_slice(whole);
    line.push(b'.');
    if tenth != 0 {
        line.push(b'0' + tenth as u8);
    }
}

fn pad(line: &mut Vec<u8>, width: usize, len: usize) {
    line.resize(line.len() + width.saturating_sub(len), b' ');
}
